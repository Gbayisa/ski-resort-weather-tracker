import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/**
 * PostgreSQL everywhere. Production talks to Cloud SQL through `pg`, configured with the standard
 * PG* variables (PGHOST may be a Cloud SQL socket directory such as /cloudsql/project:region:instance)
 * or DATABASE_URL. Without those, an embedded PGlite runs in-process: in memory when
 * DB_PATH=':memory:' (tests), otherwise on disk for local development.
 *
 * Queries use `?` placeholders, converted to $1, $2…; none of our SQL has a literal question mark.
 */
const USE_SERVER = Boolean(process.env.DATABASE_URL || process.env.PGHOST);
const DB_PATH = process.env.DB_PATH || path.join(__dirname, '..', 'data', 'pglite');

/** SQL expression for "now" in the ISO format the app stores timestamps in (same as Date#toISOString). */
export const NOW_SQL = `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;

const toPg = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

/** The query API handed to callers; `exec(sql, params)` resolves to { rows, rowCount }. */
function api(exec) {
  return {
    all: async (sql, ...params) => (await exec(sql, params)).rows,
    get: async (sql, ...params) => (await exec(sql, params)).rows[0],
    run: async (sql, ...params) => {
      const { rows, rowCount } = await exec(sql, params);
      return { changes: rowCount, rows };
    },
    /** INSERT returning the new row's id. */
    insert: async (sql, ...params) => (await exec(`${sql} RETURNING id`, params)).rows[0]?.id,
  };
}

let db;
let closeDriver;

async function connectServer() {
  const { default: pg } = await import('pg');
  // COUNT/SUM come back as int8 and AVG as numeric; both fit comfortably in a JS number here
  pg.types.setTypeParser(20, Number);
  pg.types.setTypeParser(1700, Number);
  const pool = new pg.Pool({
    connectionString: process.env.DATABASE_URL,
    max: Number(process.env.PG_POOL_MAX || 5),
  });
  const exec = (sql, params) => pool.query(toPg(sql), params);
  const tx = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(api((sql, params) => client.query(toPg(sql), params)));
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK');
      throw err;
    } finally {
      client.release();
    }
  };
  closeDriver = () => pool.end();
  return { ...api(exec), tx, exec: (sql) => pool.query(sql), label: 'PostgreSQL server' };
}

async function connectEmbedded() {
  const { PGlite, types } = await import('@electric-sql/pglite');
  const memory = DB_PATH === ':memory:';
  if (!memory) fs.mkdirSync(DB_PATH, { recursive: true });
  const lite = new PGlite(memory ? undefined : DB_PATH, { parsers: { [types.NUMERIC]: Number } });
  const shape = (r) => ({ rows: r.rows, rowCount: r.affectedRows ?? r.rows.length });
  const exec = async (sql, params) => shape(await lite.query(toPg(sql), params));
  const tx = (fn) => lite.transaction((t) => fn(api(async (sql, params) => shape(await t.query(toPg(sql), params)))));
  closeDriver = () => lite.close();
  return { ...api(exec), tx, exec: (sql) => lite.exec(sql), label: memory ? 'embedded PostgreSQL (memory)' : `embedded PostgreSQL at ${DB_PATH}` };
}

export function getDb() {
  if (!db) throw new Error('Database not initialised: call initDb() first');
  return db;
}

export async function closeDb() {
  if (closeDriver) await closeDriver();
  db = undefined;
  closeDriver = undefined;
}

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS resorts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    country TEXT,
    region TEXT,
    website TEXT,
    osm_id TEXT UNIQUE,
    elevation_base INTEGER DEFAULT 0,
    elevation_peak INTEGER DEFAULT 0,
    piste_km DOUBLE PRECISION,
    lifts INTEGER,
    snowparks INTEGER,
    pct_easy INTEGER,
    pct_intermediate INTEGER,
    pct_advanced INTEGER,
    updated_at TEXT DEFAULT (${NOW_SQL})
  );

  -- One cached forecast per resort covers every date; last_used_at lets the scheduler refresh only hot ones
  CREATE TABLE IF NOT EXISTS resort_forecasts (
    resort_id INTEGER PRIMARY KEY REFERENCES resorts(id),
    data TEXT NOT NULL,
    fetched_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_used_at TEXT
  );

  CREATE TABLE IF NOT EXISTS route_cache (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_key TEXT NOT NULL,
    resort_id INTEGER NOT NULL REFERENCES resorts(id),
    distance_km DOUBLE PRECISION,
    duration_min DOUBLE PRECISION,
    source TEXT,
    fetched_at TEXT DEFAULT (${NOW_SQL}),
    expires_at TEXT NOT NULL,
    UNIQUE (origin_key, resort_id)
  );

  -- ===== Community (meet riders on the mountain) =====
  -- Accounts are device tokens (only the SHA-256 hash is stored).
  CREATE TABLE IF NOT EXISTS riders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    age INTEGER NOT NULL CHECK (age >= 18),
    sport TEXT NOT NULL,
    gender TEXT NOT NULL,
    level TEXT NOT NULL,
    bio TEXT DEFAULT '',
    visibility TEXT NOT NULL DEFAULT 'everyone',
    avatar TEXT NOT NULL,
    avatar_config TEXT,
    tags TEXT NOT NULL DEFAULT '[]',
    home_resort_id INTEGER REFERENCES resorts(id),
    riders_met INTEGER NOT NULL DEFAULT 0,
    instagram TEXT,
    instagram_visibility TEXT NOT NULL DEFAULT 'connections',
    is_demo INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (${NOW_SQL}),
    updated_at TEXT NOT NULL DEFAULT (${NOW_SQL})
  );

  -- Resort-level presence only: no coordinates are ever stored.
  CREATE TABLE IF NOT EXISTS checkins (
    rider_id INTEGER PRIMARY KEY REFERENCES riders(id) ON DELETE CASCADE,
    resort_id INTEGER NOT NULL REFERENCES resorts(id),
    intents TEXT NOT NULL DEFAULT '[]',
    note TEXT DEFAULT '',
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_checkins_resort ON checkins(resort_id, expires_at);

  CREATE TABLE IF NOT EXISTS connections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_rider INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    to_rider INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    resort_id INTEGER NOT NULL REFERENCES resorts(id),
    intent TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_connections_riders ON connections(from_rider, to_rider);

  CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id INTEGER NOT NULL REFERENCES connections(id) ON DELETE CASCADE,
    from_rider INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    created_at TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_messages_connection ON messages(connection_id, id);

  CREATE TABLE IF NOT EXISTS blocks (
    blocker INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    blocked INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT (${NOW_SQL}),
    PRIMARY KEY (blocker, blocked)
  );

  -- One row per rider per resort per day checked in: powers season stats and badges.
  -- Resort-level and deleted with the profile, like everything else.
  CREATE TABLE IF NOT EXISTS rider_days (
    rider_id INTEGER NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
    resort_id INTEGER NOT NULL REFERENCES resorts(id),
    day TEXT NOT NULL,
    PRIMARY KEY (rider_id, day, resort_id)
  );

  CREATE TABLE IF NOT EXISTS reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter INTEGER REFERENCES riders(id) ON DELETE SET NULL,
    reported INTEGER REFERENCES riders(id) ON DELETE SET NULL,
    reason TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (${NOW_SQL})
  );

  -- Small key/value store, e.g. which version of the resort catalogue is loaded
  CREATE TABLE IF NOT EXISTS app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );

  CREATE INDEX IF NOT EXISTS idx_resorts_lat_lon ON resorts(lat, lon);
  CREATE INDEX IF NOT EXISTS idx_resort_forecasts_expires ON resort_forecasts(expires_at);
  CREATE INDEX IF NOT EXISTS idx_route_cache_expires ON route_cache(expires_at);
`;

export async function initDb() {
  if (db) return db;
  db = USE_SERVER ? await connectServer() : await connectEmbedded();
  await db.exec(SCHEMA);
  if (process.env.NODE_ENV !== 'test') console.log('Database ready:', db.label);
  return db;
}
